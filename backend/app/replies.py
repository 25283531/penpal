"""Reply scheduler: generate replies for due letters, nothing else.

A letter is only 'replied' when a reply was actually generated by the
LLM, passed the content filter, and stored. Without an LLM key the
letter stays in_transit with status "queued" — a reply is NEVER faked.

`process_due_replies(device_id, day)` is the manual trigger endpoint
used by tests and by a daily job in production. `day` is injectable so
tests can simulate "3 days later" without waiting.
"""
from datetime import date

from . import database, evolution
from .context import build_reply_context
from .llm import LLMError, LLMNotConfigured, generate_reply_text


def process_due_replies(device_id: str, day: str | None = None) -> dict:
    """Process this device's due letters for `day` (default today).

    Returns {"processed": n, "replied": n, "queued": n, "failed": n,
    "llm_unavailable": bool, "details": [...]}. `queued` counts letters
    whose reply is not due yet OR could not be generated because no LLM
    is configured — both stay in_transit, honestly.
    """
    today = day or date.today().isoformat()
    due = database.due_user_letters(device_id, today)
    result = {
        "processed": 0,
        "replied": 0,
        "queued": 0,
        "failed": 0,
        "llm_unavailable": False,
        "details": [],
    }
    for letter in due:
        result["processed"] += 1
        char = database.character_for_llm(letter["character_id"], device_id)
        if not char:
            result["failed"] += 1
            result["details"].append({"letter_id": letter["id"], "status": "character_not_found",
                                      "code": "character_not_found"})
            continue
        try:
            context = build_reply_context(device_id, letter["character_id"])
            text = generate_reply_text(char, letter["text"], context=context)
        except LLMNotConfigured:
            result["queued"] += 1
            result["llm_unavailable"] = True
            result["details"].append({"letter_id": letter["id"], "status": "queued_no_llm",
                                      "code": "llm_not_configured"})
            continue
        except LLMError as e:
            result["failed"] += 1
            code = ("content_filter_failed" if "content filter" in str(e)
                    else "reply_generation_failed")
            result["details"].append({"letter_id": letter["id"], "status": "failed",
                                      "code": code, "error": str(e)[:200]})
            continue
        reply = database.create_reply_letter(device_id, letter["character_id"], text)
        # mark_letter_replied also records character_read_at on the
        # user's letter (derived: replied_at minus up to 3h, clamped
        # inside [sent, replied], minute precision — see database.py).
        database.mark_letter_replied(device_id, letter["id"])
        # Consolidation only — do NOT count the reply as an interaction:
        # interaction_count counts user letters (it drives the stage
        # thresholds), so counting replies here would advance stages
        # twice as fast.
        try:
            if evolution.consolidation_due(device_id, letter["character_id"]):
                evolution.run_consolidation(device_id, letter["character_id"])
        except Exception:
            pass
        result["replied"] += 1
        result["details"].append({"letter_id": letter["id"], "reply_id": reply["id"], "status": "replied"})
    return result
